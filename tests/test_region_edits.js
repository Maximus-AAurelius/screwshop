const assert = require('node:assert/strict');
const fs = require('fs'), vm = require('vm');
let id = 0;
const sandbox = { window: { ScrewShop: { id: () => String(++id) }, addEventListener() {} }, document: { addEventListener() {} }, setInterval() {}, confirm: () => true };
vm.runInNewContext(fs.readFileSync('docs/recording-studio.js', 'utf8'), sandbox);
const s = new sandbox.window.RecordingStudio({ setState() {} });
s.save = () => {}; s.refresh = () => {};
s.tracks = [{ id: 't', clips: [{ id: 'a', name: 'Vocal', url: 'audio', start: 0, length: 10 }] }];
s.buffers.set('audio', { duration: 10 });
s.cursor = 0.02; s.splitClipAtPlayhead('a');
assert.equal(s.tracks[0].clips[0].length, 0.02, 'short cuts must not expand');
let right = s.tracks[0].clips[1];
assert.equal(right.sourceOffset, 0.02);
s.cursor = 4; s.splitClipAtPlayhead(right.id);
right = s.tracks[0].clips[2]; assert.equal(right.sourceOffset, 4);
s.moveClip(right.id, 't', 12);
const starts = [];
s.ctx = { createBufferSource: () => ({ playbackRate: {}, connect() {}, start(...args) { starts.push(args); } }) };
s.trackGains = new Map([['t', {}]]);
s.schedulePass(12, 18, 0);
assert.deepEqual(starts[0], [0, 4, 6], 'moved right region must play its original audio slice');
s.deleteClip(right.id); assert.equal(s.tracks[0].clips.length, 2);
s.undo(); assert.equal(s.tracks[0].clips[2].sourceOffset, 4);
s.undo(true); assert.equal(s.tracks[0].clips.length, 2);
s.tracks[0].locked = true; s.cursor = 2; s.splitClipAtPlayhead(s.tracks[0].clips[1].id);
assert.equal(s.tracks[0].clips.length, 2);
s.tracks[0].locked = false;
s.tracks.push({ id: 'locked', locked: true, clips: [] });
const moving = s.tracks[0].clips[1], beforeMove = JSON.stringify(s.tracks);
s.moveClip(moving.id, 'locked', 25);
assert.equal(JSON.stringify(s.tracks), beforeMove, 'a locked destination must reject a region without moving its source');
s.deleteTrack('locked');
assert.equal(s.tracks.length, 2, 'locked tracks cannot be deleted');
s.deleteTrack('t');
assert.equal(s.tracks.length, 1);
s.undo();
assert.equal(s.tracks.length, 2, 'track deletion must be undoable');
assert.equal(s.tracks[0].clips[1].sourceOffset, 0.02, 'undo restores the original audio slices');

(async () => {
  let decoded = false;
  s.decode = async () => { decoded = true; };
  await s.addClip('locked', { url: 'new-audio', name: 'Import' }, 0);
  assert.equal(decoded, false, 'locked tracks must reject audio before decoding');
  assert.equal(s.tracks[1].clips.length, 0);
  s.tracks[1].locked = false;
  let release;
  s.decode = () => new Promise(resolve => { release = resolve; });
  const pendingImport = s.addClip('locked', { url: 'new-audio', name: 'Import' }, 0);
  s.tracks[1].locked = true;
  release(); await pendingImport;
  assert.equal(s.tracks[1].clips.length, 0, 'a track locked while audio loads must stay unchanged');
  s.tracks[1].locked = false; s.decode = async () => {};
  await s.addClip('locked', { url: 'new-audio', name: 'Import' }, 0);
  assert.equal(s.tracks[1].clips.length, 1);
  s.undo(); assert.equal(s.tracks[1].clips.length, 0, 'adding imported audio must be undoable');
  const snapshots=[]; s.save=()=>snapshots.push(JSON.stringify(s.tracks));
  const imported=await s.addClip(null, {url:'compound-import',name:'New track'},0);
  assert.ok(imported?.id);
  assert.equal(snapshots.length,1,'a compound import saves one complete arrangement');
  assert.equal(JSON.parse(snapshots[0]).at(-1).clips.length,1,'the new track must never be saved before its clip');
  snapshots.length=0;
  s.moveClip(imported.id,'__new',4);
  assert.equal(snapshots.length,1,'moving audio to a new track saves one complete arrangement');
  const moved=JSON.parse(snapshots[0]);
  assert.equal(moved.at(-2).clips.length,0);assert.equal(moved.at(-1).clips[0].id,imported.id);
  console.log('PASS: exact splits, moved audio scheduling, delete, undo/redo, destination locks, import races, undoable track deletion/import');
})().catch(error => { console.error(error); process.exitCode = 1; });

const assert = require('node:assert/strict');
const fs = require('fs'), vm = require('vm');
let id = 0;
const sandbox = { window: { ScrewShop: { id: () => String(++id) }, addEventListener() {} }, document: { addEventListener() {} }, setInterval() {} };
vm.runInNewContext(fs.readFileSync('docs/recording-studio.js', 'utf8'), sandbox);
const s = new sandbox.window.RecordingStudio({ setState() {} });
s.save = () => {}; s.refresh = () => {};
s.tracks = [{ id: 't', clips: [{ id: 'a', name: 'Vocal', url: 'audio', start: 0, length: 10 }] }];
s.buffers.set('audio', { duration: 10 });
s.cursor = 0.02; s.splitClipAtPlayhead('a');
assert.equal(s.tracks[0].clips[0].length, 0.02, 'short cuts must not expand');
let right = s.tracks[0].clips[1];
assert.equal(right.sourceOffset, 0.02);
s.cursor = 4; s.splitClipAtPlayhead(right.id);
right = s.tracks[0].clips[2]; assert.equal(right.sourceOffset, 4);
s.moveClip(right.id, 't', 12);
const starts = [];
s.ctx = { createBufferSource: () => ({ playbackRate: {}, connect() {}, start(...args) { starts.push(args); } }) };
s.trackGains = new Map([['t', {}]]);
s.schedulePass(12, 18, 0);
assert.deepEqual(starts[0], [0, 4, 6], 'moved right region must play its original audio slice');
s.deleteClip(right.id); assert.equal(s.tracks[0].clips.length, 2);
s.undo(); assert.equal(s.tracks[0].clips[2].sourceOffset, 4);
s.undo(true); assert.equal(s.tracks[0].clips.length, 2);
s.tracks[0].locked = true; s.cursor = 2; s.splitClipAtPlayhead(s.tracks[0].clips[1].id);
assert.equal(s.tracks[0].clips.length, 2);
console.log('PASS: exact short splits, repeated splits, moved audio scheduling, delete, undo/redo, locks');
